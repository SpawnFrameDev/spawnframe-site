"""Build functions/_lib/recipes.js (every WoW Forever recipe: name, output, quantity, materials) from
GoldCraftForever's Data/RecipeData.lua, for the public market pages. Re-run after a game patch:
  python3 tools/build_market_recipes.py ../GoldCraftForever/Data/RecipeData.lua"""
import json, sys, pathlib, lupa
src = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
L = lupa.LuaRuntime(unpack_returned_tuples=True)
L.execute("ns = {}")
L.execute(src.replace("local _, ns = ...", ""))
data = L.globals().ns.RecipeData
out = {"build": data.build, "professions": {}}
for prof in data.keys():
    if prof == "build":
        continue
    rows = []
    for rid, r in data[prof].items():
        name, item, qty = r[1], int(r[2]), int(r[3])
        if item <= 0:
            continue                                    # enchants and other recipes with no item to sell
        mats = list(r[6].values()) if r[6] else []
        rows.append([name, item, qty, [int(x) for x in mats], int(r[9] or 0)])
    rows.sort(key=lambda x: x[0])
    out["professions"][prof] = rows
js = ("// Generated by tools/build_market_recipes.py from GoldCraftForever's recipe data. Do not edit.\n"
      "export default " + json.dumps(out, separators=(",", ":")) + ";\n")
pathlib.Path(__file__).resolve().parent.parent.joinpath("functions/_lib/recipes.js").write_text(js, encoding="utf-8")
ids = {r[1] for p in out["professions"].values() for r in p} | {m for p in out["professions"].values() for r in p for m in r[3][0::2]}
print({k: len(v) for k, v in out["professions"].items()}, "unique items:", len(ids), "bytes:", len(js))
